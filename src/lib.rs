//! Narrow, evidence-bounded Rust emission for the Delphi Stage-1 scalar fixture.

use serde::Deserialize;
use std::fmt::Write;

#[derive(Debug, Deserialize)]
pub struct FactDocument {
    pub source_language: String,
    pub variant: Variant,
    pub facts: Vec<ScalarAdditionFunction>,
}

#[derive(Debug, Deserialize)]
pub struct Variant {
    pub compiler: Compiler,
}

#[derive(Debug, Deserialize)]
pub struct Compiler {
    pub family: String,
    pub version: String,
    pub target_cpu: String,
    pub target_os: String,
    pub mode: String,
}

#[derive(Debug, Deserialize)]
pub struct ScalarAdditionFunction {
    pub kind: String,
    pub name: String,
    pub parameters: Vec<Parameter>,
    pub return_type: String,
    pub operands: Vec<String>,
}

#[derive(Debug, Deserialize)]
pub struct Parameter {
    pub name: String,
    #[serde(rename = "type")]
    pub source_type: String,
}

pub fn emit_scalar_additions(input: &str) -> Result<String, String> {
    let document: FactDocument =
        serde_json::from_str(input).map_err(|error| format!("invalid source facts: {error}"))?;
    if document.source_language != "delphi" {
        return Err("only Delphi source facts are supported".to_owned());
    }
    validate_variant(&document.variant)?;
    if document.facts.is_empty() {
        return Err("no scalar addition facts were supplied".to_owned());
    }
    let mut output = String::from("// Generated by sourcebridge-rust; do not edit.\n\n");
    for fact in &document.facts {
        emit_function(&mut output, fact)?;
    }
    Ok(output)
}

#[derive(Debug, Deserialize)]
pub struct CFactDocument {
    pub fact_schema: String,
    pub source: CSource,
    pub variant: CVariant,
    pub functions: Vec<CMainFunction>,
}

#[derive(Debug, Deserialize)]
pub struct CSource {
    pub path: String,
    pub sha256: String,
}

#[derive(Debug, Deserialize)]
pub struct CVariant {
    pub compiler: CCompiler,
    pub target: String,
    pub standard: String,
    pub optimization: String,
}

#[derive(Debug, Deserialize)]
pub struct CCompiler {
    pub command: String,
    pub version: String,
}

#[derive(Debug, Deserialize)]
pub struct CMainFunction {
    pub name: String,
    pub return_type: String,
    pub return_expression: CExpression,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "kind")]
pub enum CExpression {
    #[serde(rename = "integer_literal")]
    IntegerLiteral {
        #[serde(rename = "type")]
        source_type: String,
        value: i64,
    },
    #[serde(rename = "binary_operator")]
    BinaryOperator {
        operator: String,
        #[serde(rename = "type")]
        source_type: String,
        left: Box<CExpression>,
        right: Box<CExpression>,
    },
}

pub fn emit_c_main_exit(input: &str) -> Result<String, String> {
    let document: CFactDocument =
        serde_json::from_str(input).map_err(|error| format!("invalid C source facts: {error}"))?;
    if document.fact_schema != "sourcebridge.c.ast-facts.v1" {
        return Err(format!("unsupported C fact schema `{}`", document.fact_schema));
    }
    validate_c_variant(&document.variant)?;
    if document.source.path.is_empty() || document.source.sha256.len() != 64 {
        return Err("C source provenance is incomplete".to_owned());
    }
    if document.functions.len() != 1 {
        return Err("exactly one C main function is required".to_owned());
    }
    let function = &document.functions[0];
    if function.name != "main" || function.return_type != "int" {
        return Err("only an int main function is supported".to_owned());
    }
    let (expression, _) = emit_c_expression(&function.return_expression)?;
    let expression = expression
        .strip_prefix('(')
        .and_then(|value| value.strip_suffix(')'))
        .unwrap_or(&expression);
    Ok(format!(
        "// Generated by sourcebridge-rust; do not edit.\n\nfn main() {{\n    let exit_code: i32 = {expression};\n    std::process::exit(exit_code);\n}}\n"
    ))
}

fn validate_c_variant(variant: &CVariant) -> Result<(), String> {
    if variant.compiler.command == "clang"
        && variant.compiler.version == "22.1.8"
        && variant.target == "x86_64-redhat-linux-gnu"
        && variant.standard == "c11"
        && variant.optimization == "O0"
    {
        Ok(())
    } else {
        Err("unsupported C compiler variant for native Rust lowering".to_owned())
    }
}

fn emit_c_expression(expression: &CExpression) -> Result<(String, i32), String> {
    match expression {
        CExpression::IntegerLiteral { source_type, value } => {
            if source_type != "int" {
                return Err(format!("unsupported C integer type `{source_type}`"));
            }
            let value = i32::try_from(*value)
                .map_err(|_| format!("C integer literal `{value}` is outside i32"))?;
            Ok((format!("{value}i32"), value))
        }
        CExpression::BinaryOperator {
            operator,
            source_type,
            left,
            right,
        } => {
            if source_type != "int" {
                return Err(format!("unsupported C binary result type `{source_type}`"));
            }
            let (left_source, left_value) = emit_c_expression(left)?;
            let (right_source, right_value) = emit_c_expression(right)?;
            let value = match operator.as_str() {
                "+" => left_value.checked_add(right_value),
                "-" => left_value.checked_sub(right_value),
                "*" => left_value.checked_mul(right_value),
                other => return Err(format!("unsupported C binary operator `{other}`")),
            }
            .ok_or_else(|| {
                format!(
                    "C expression `{left_value} {operator} {right_value}` requires an overflow policy"
                )
            })?;
            Ok((format!("({left_source} {operator} {right_source})"), value))
        }
    }
}

fn validate_variant(variant: &Variant) -> Result<(), String> {
    let compiler = &variant.compiler;
    if compiler.family == "free-pascal"
        && compiler.version == "3.2.3"
        && compiler.target_cpu == "x86_64"
        && compiler.target_os == "linux"
        && compiler.mode == "delphi"
    {
        Ok(())
    } else {
        Err("unsupported source compiler variant for scalar type mapping".to_owned())
    }
}

fn emit_function(output: &mut String, fact: &ScalarAdditionFunction) -> Result<(), String> {
    if fact.kind != "scalar_addition_function" {
        return Err(format!("unsupported fact kind `{}`", fact.kind));
    }
    if fact.parameters.len() != 2 || fact.operands.len() != 2 {
        return Err(format!("{} must have exactly two parameters and operands", fact.name));
    }
    let rust_type = map_type(&fact.return_type)?;
    if fact.parameters.iter().any(|parameter| map_type(&parameter.source_type) != Ok(rust_type)) {
        return Err(format!("{} has mismatched parameter and return types", fact.name));
    }
    if fact
        .operands
        .iter()
        .zip(&fact.parameters)
        .any(|(operand, parameter)| operand != &parameter.name)
    {
        return Err(format!("{} operands must match declared parameter order", fact.name));
    }
    writeln!(
        output,
        "pub fn {}({}: {}, {}: {}) -> {} {{",
        snake_case(&fact.name),
        snake_case(&fact.parameters[0].name),
        rust_type,
        snake_case(&fact.parameters[1].name),
        rust_type,
        rust_type,
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    {}.wrapping_add({})",
        snake_case(&fact.parameters[0].name),
        snake_case(&fact.parameters[1].name),
    )
    .expect("writing to String cannot fail");
    writeln!(output, "}}\n").expect("writing to String cannot fail");
    Ok(())
}

fn map_type(source_type: &str) -> Result<&'static str, String> {
    match source_type {
        "integer" => Ok("i32"),
        "cardinal" => Ok("u32"),
        other => Err(format!("unsupported Delphi scalar type `{other}`")),
    }
}

fn snake_case(name: &str) -> String {
    let mut output = String::new();
    for (index, character) in name.chars().enumerate() {
        if character.is_uppercase() && index > 0 {
            output.push('_');
        }
        output.extend(character.to_lowercase());
    }
    output
}

#[cfg(test)]
mod tests {
    use super::{emit_c_main_exit, emit_scalar_additions};

    #[test]
    fn emits_verified_scalar_functions() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.3","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddSigned",
            "parameters":[{"name":"Left","type":"integer"},{"name":"Right","type":"integer"}],
            "return_type":"integer",
            "operands":["Left","Right"]
          }]
        }"#;
        let output = emit_scalar_additions(facts).expect("fixture facts should emit");
        assert!(output.contains("pub fn add_signed(left: i32, right: i32) -> i32"));
        assert!(output.contains("left.wrapping_add(right)"));
    }

    #[test]
    fn rejects_unverified_source_type() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.3","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddWide",
            "parameters":[{"name":"Left","type":"int64"},{"name":"Right","type":"int64"}],
            "return_type":"int64",
            "operands":["Left","Right"]
          }]
        }"#;
        assert!(emit_scalar_additions(facts).is_err());
    }

    #[test]
    fn rejects_unpinned_compiler_variant() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.4","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddSigned",
            "parameters":[{"name":"Left","type":"integer"},{"name":"Right","type":"integer"}],
            "return_type":"integer",
            "operands":["Left","Right"]
          }]
        }"#;
        assert!(emit_scalar_additions(facts).is_err());
    }

    #[test]
    fn emits_verified_c_main_exit() {
        let facts = r#"{
          "fact_schema":"sourcebridge.c.ast-facts.v1",
          "source":{"path":"tests/single-exec/00002.c","sha256":"343dee856433f5cae74d3e0f56fb2f4fc25256172c3028fdd3d393541cc8bd33"},
          "variant":{"compiler":{"command":"clang","version":"22.1.8"},"target":"x86_64-redhat-linux-gnu","standard":"c11","optimization":"O0"},
          "functions":[{"name":"main","return_type":"int","return_expression":{"kind":"binary_operator","operator":"-","type":"int","left":{"kind":"integer_literal","type":"int","value":3},"right":{"kind":"integer_literal","type":"int","value":3}}}]
        }"#;
        let output = emit_c_main_exit(facts).expect("verified C facts should emit");
        assert!(output.contains("let exit_code: i32 = 3i32 - 3i32;"));
    }

    #[test]
    fn rejects_c_expression_without_overflow_policy() {
        let facts = r#"{
          "fact_schema":"sourcebridge.c.ast-facts.v1",
          "source":{"path":"tests/single-exec/overflow.c","sha256":"343dee856433f5cae74d3e0f56fb2f4fc25256172c3028fdd3d393541cc8bd33"},
          "variant":{"compiler":{"command":"clang","version":"22.1.8"},"target":"x86_64-redhat-linux-gnu","standard":"c11","optimization":"O0"},
          "functions":[{"name":"main","return_type":"int","return_expression":{"kind":"binary_operator","operator":"+","type":"int","left":{"kind":"integer_literal","type":"int","value":2147483647},"right":{"kind":"integer_literal","type":"int","value":1}}}]
        }"#;
        assert!(emit_c_main_exit(facts).is_err());
    }
}
