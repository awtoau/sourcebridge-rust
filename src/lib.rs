//! Narrow, evidence-bounded Rust emission for the Delphi Stage-1 scalar fixture.

use serde::Deserialize;
use std::fmt::Write;

#[derive(Debug, Deserialize)]
pub struct FactDocument {
    pub source_language: String,
    pub variant: Variant,
    pub facts: Vec<ScalarAdditionFunction>,
}

#[derive(Debug, Deserialize)]
pub struct Variant {
    pub compiler: Compiler,
}

#[derive(Debug, Deserialize)]
pub struct Compiler {
    pub family: String,
    pub version: String,
    pub target_cpu: String,
    pub target_os: String,
    pub mode: String,
}

#[derive(Debug, Deserialize)]
pub struct ScalarAdditionFunction {
    pub kind: String,
    pub name: String,
    pub parameters: Vec<Parameter>,
    pub return_type: String,
    pub operands: Vec<String>,
}

#[derive(Debug, Deserialize)]
pub struct Parameter {
    pub name: String,
    #[serde(rename = "type")]
    pub source_type: String,
}

pub fn emit_scalar_additions(input: &str) -> Result<String, String> {
    let document: FactDocument =
        serde_json::from_str(input).map_err(|error| format!("invalid source facts: {error}"))?;
    if document.source_language != "delphi" {
        return Err("only Delphi source facts are supported".to_owned());
    }
    validate_variant(&document.variant)?;
    if document.facts.is_empty() {
        return Err("no scalar addition facts were supplied".to_owned());
    }
    let mut output = String::from("// Generated by sourcebridge-rust; do not edit.\n\n");
    for fact in &document.facts {
        emit_function(&mut output, fact)?;
    }
    Ok(output)
}

fn validate_variant(variant: &Variant) -> Result<(), String> {
    let compiler = &variant.compiler;
    if compiler.family == "free-pascal"
        && compiler.version == "3.2.3"
        && compiler.target_cpu == "x86_64"
        && compiler.target_os == "linux"
        && compiler.mode == "delphi"
    {
        Ok(())
    } else {
        Err("unsupported source compiler variant for scalar type mapping".to_owned())
    }
}

fn emit_function(output: &mut String, fact: &ScalarAdditionFunction) -> Result<(), String> {
    if fact.kind != "scalar_addition_function" {
        return Err(format!("unsupported fact kind `{}`", fact.kind));
    }
    if fact.parameters.len() != 2 || fact.operands.len() != 2 {
        return Err(format!("{} must have exactly two parameters and operands", fact.name));
    }
    let rust_type = map_type(&fact.return_type)?;
    if fact.parameters.iter().any(|parameter| map_type(&parameter.source_type) != Ok(rust_type)) {
        return Err(format!("{} has mismatched parameter and return types", fact.name));
    }
    if fact
        .operands
        .iter()
        .zip(&fact.parameters)
        .any(|(operand, parameter)| operand != &parameter.name)
    {
        return Err(format!("{} operands must match declared parameter order", fact.name));
    }
    writeln!(
        output,
        "pub fn {}({}: {}, {}: {}) -> {} {{",
        snake_case(&fact.name),
        snake_case(&fact.parameters[0].name),
        rust_type,
        snake_case(&fact.parameters[1].name),
        rust_type,
        rust_type,
    )
    .expect("writing to String cannot fail");
    writeln!(
        output,
        "    {} + {}",
        snake_case(&fact.parameters[0].name),
        snake_case(&fact.parameters[1].name),
    )
    .expect("writing to String cannot fail");
    writeln!(output, "}}\n").expect("writing to String cannot fail");
    Ok(())
}

fn map_type(source_type: &str) -> Result<&'static str, String> {
    match source_type {
        "integer" => Ok("i32"),
        "cardinal" => Ok("u32"),
        other => Err(format!("unsupported Delphi scalar type `{other}`")),
    }
}

fn snake_case(name: &str) -> String {
    let mut output = String::new();
    for (index, character) in name.chars().enumerate() {
        if character.is_uppercase() && index > 0 {
            output.push('_');
        }
        output.extend(character.to_lowercase());
    }
    output
}

#[cfg(test)]
mod tests {
    use super::emit_scalar_additions;

    #[test]
    fn emits_verified_scalar_functions() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.3","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddSigned",
            "parameters":[{"name":"Left","type":"integer"},{"name":"Right","type":"integer"}],
            "return_type":"integer",
            "operands":["Left","Right"]
          }]
        }"#;
        let output = emit_scalar_additions(facts).expect("fixture facts should emit");
        assert!(output.contains("pub fn add_signed(left: i32, right: i32) -> i32"));
        assert!(output.contains("left + right"));
    }

    #[test]
    fn rejects_unverified_source_type() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.3","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddWide",
            "parameters":[{"name":"Left","type":"int64"},{"name":"Right","type":"int64"}],
            "return_type":"int64",
            "operands":["Left","Right"]
          }]
        }"#;
        assert!(emit_scalar_additions(facts).is_err());
    }

    #[test]
    fn rejects_unpinned_compiler_variant() {
        let facts = r#"{
          "source_language":"delphi",
          "variant":{"compiler":{"family":"free-pascal","version":"3.2.4","target_cpu":"x86_64","target_os":"linux","mode":"delphi"}},
          "facts":[{
            "kind":"scalar_addition_function",
            "name":"AddSigned",
            "parameters":[{"name":"Left","type":"integer"},{"name":"Right","type":"integer"}],
            "return_type":"integer",
            "operands":["Left","Right"]
          }]
        }"#;
        assert!(emit_scalar_additions(facts).is_err());
    }
}
